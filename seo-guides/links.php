                        <h2 class="card-title text-primary mb-3">What are Links?</h2>
                        <p class="card-text mb-3">
                            Links (also called hyperlinks) are clickable elements that connect web pages together. They consist of anchor text (the visible, clickable text) and a destination URL. Links are fundamental to the web's structure and play a crucial role in SEO.
                        </p>
                        <p class="card-text mb-0">
                            There are two main types of links: <strong>internal links</strong> (connecting pages within your website) and <strong>external links</strong> (connecting to other websites). Each type serves different purposes for SEO and user experience.
                        </p>

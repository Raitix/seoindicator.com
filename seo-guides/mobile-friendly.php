                        <div class="row">
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">📱 Responsive Design</h5>
                                <ul>
                                    <li><strong>Viewport Meta Tag:</strong> Use proper viewport configuration</li>
                                    <li><strong>Flexible Layouts:</strong> CSS Grid and Flexbox for responsive layouts</li>
                                    <li><strong>Media Queries:</strong> CSS breakpoints for different screen sizes</li>
                                    <li><strong>Fluid Images:</strong> Images that scale with container width</li>
                                </ul>
                            </div>
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">⚡ Performance Optimization</h5>
                                <ul>
                                    <li><strong>Fast Loading:</strong> Optimize for 3-second load times or less</li>
                                    <li><strong>Compressed Images:</strong> Use WebP format and proper sizing</li>
                                    <li><strong>Minified Code:</strong> Compress CSS, JavaScript, and HTML</li>
                                    <li><strong>Lazy Loading:</strong> Load images and content as needed</li>
                                </ul>
                            </div>

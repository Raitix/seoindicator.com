                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">👆 Touch Interface</h5>
                                <ul>
                                    <li><strong>Touch Targets:</strong> Minimum 44px (iOS) or 48dp (Android) button size</li>
                                    <li><strong>Spacing:</strong> Adequate space between clickable elements</li>
                                    <li><strong>Navigation:</strong> Use hamburger menus. Place CTAs (Call to Action) buttons mid-screen</li>
                                    <li><strong>Forms:</strong> Large input fields with appropriate keyboard types</li>
                                    <li><strong>user-scalable=no:</strong> Do not use this meta tag! Disabling zoom harms accessibility (WCAG compliance)</li>
                                    <li><strong>Avoid Pop-Ups:</strong> Pop-ups can lead to Google penalties</li>
                                </ul>
                            </div>
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">📖 Content & Typography</h5>
                                <ul>
                                    <li><strong>Readable Fonts:</strong> Minimum 16px font size for body text</li>
                                    <li><strong>Contrast:</strong> High contrast ratios for readability</li>
                                    <li><strong>Content Priority:</strong> Most important content above the fold (first impression visible without scrolling)</li>
                                    <li><strong>Scannable Text:</strong> Short paragraphs and clear headings</li>
                                    <li><strong>Content Parity:</strong> Ensure mobile + desktop have identical text, images, videos, page structure, meta titles and meta descriptions</li>
                                </ul>
                            </div>

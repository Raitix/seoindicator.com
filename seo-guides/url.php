                            <code>✅ https://example.com/seo-guide-for-beginners</code><br>
                            <code>✅ https://example.com/products/wireless-headphones</code><br>
                            <code>❌ https://example.com/page123.php?id=456&cat=789</code><br>
                            <code>❌ http://example.com/Product%20Page%20Title</code>
                        </div>

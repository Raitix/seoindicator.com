                <div class="card bg-dark border-secondary mb-4">
                    <div class="card-body">
                        <h2 class="card-title text-warning mb-3">URL SEO Best Practices</h2>
                        
                        <div class="row">
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">🔒 Security & Protocol</h5>
                                <ul>
                                    <li>Use <strong>HTTPS</strong> for all pages</li>
                                    <li>Ensure SSL certificate is valid</li>
                                    <li>Avoid mixed content warnings</li>
                                    <li>Redirect HTTP to HTTPS</li>
                                </ul>
                            </div>
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">🌐 Domain Optimization</h5>
                                <ul>
                                    <li>Choose <strong>brandable domain names</strong></li>
                                    <li>Use popular TLDs (.com, .org, .net)</li>
                                    <li>Avoid hyphens and numbers in domain</li>
                                    <li>Keep domain names short and memorable</li>
                                </ul>
                            </div>
                        </div>

                        <div class="row">
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">📝 URL Structure (after domain name)</h5>
                                <ul>
                                    <li>Use <strong>lowercase letters</strong> only</li>
                                    <li>Separate words with <strong>hyphens (-)</strong></li>
                                    <li>Avoid underscores, spaces, and special characters</li>
                                    <li>Create logical hierarchical structure</li>
                                </ul>
                            </div>
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">🎯 Keyword Usage</h5>
                                <ul>
                                    <li>Include <strong>target keywords</strong> naturally</li>
                                    <li>Place important keywords closer to domain</li>
                                    <li>Avoid keyword stuffing in URLs</li>
                                    <li>Use semantic variations when appropriate</li>
                                </ul>
                            </div>
                        </div>

                        <div class="row">
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">📏 Length & Simplicity</h5>
                                <ul>
                                    <li>Keep URLs under <strong>100 characters</strong></li>
                                    <li>Aim for 3-5 path segments maximum</li>
                                    <li>Avoid unnecessarily deep folder structures</li>
                                    <li>Balance brevity with descriptiveness</li>
                                </ul>
                            </div>
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">🗂️ Organization</h5>
                                <ul>
                                    <li>Reflect <strong>site navigation</strong> in URL structure</li>
                                    <li>Use consistent patterns across the site</li>
                                    <li>Group related content logically</li>
                                    <li>Avoid dynamic parameters when possible</li>
                                </ul>
                            </div>
                        </div>
                    </div>

                        <div class="row">
                            <div class="col-md-6 mb-4">
                                <h5 class="text-info">🏗️ Subdomains vs. Subdirectories</h5>
                                <div class="mb-3">
                                    <strong class="text-success">✅ Subdirectories (preferred for SEO):</strong><br>
                                    <code>example.com/blog/</code><br>
                                    <small class="text-muted">Consolidates domain authority</small>
                                </div>
                                <div>
                                    <strong class="text-danger">❌ Subdomains (treated as separate entities):</strong><br>
                                    <code>blog.example.com</code><br>
                                    <small class="text-muted">Weakens main domain SEO</small>
                                </div>
                            </div>
                            
                            <div class="col-md-6 mb-4">
                                <h5 class="text-info">🌐 WWW Consistency</h5>
                                <ul>
                                    <li><strong>Choose WWW or non-WWW:</strong> Stick to one version</li>
                                    <li><strong>Set 301 redirects:</strong> Redirect the unused version</li>
                                    <li><strong>Update DNS:</strong> Ensure both versions work properly</li>
                                    <li><strong>Google Search Console:</strong> Set preferred domain version</li>
                                </ul>
                            </div>
                        </div>

                        <div class="row">
                            <div class="col-md-6 mb-4">
                                <h5 class="text-info">⚙️ URL Parameters & Dynamic URLs</h5>
                                <div class="mb-3">
                                    <strong>Minimize parameters - Use static URLs:</strong><br>
                                    <span class="text-success">✅ <code>example.com/categories/seo</code></span><br>
                                    <span class="text-danger">❌ <code>example.com/cat?=seo&sort=desc</code></span>
                                </div>
                                <p><strong>Canonicalize duplicate URLs:</strong> Use <code>rel="canonical"</code> if parameters are unavoidable.</p>
                            </div>
                            
                            <div class="col-md-6 mb-4">
                                <h5 class="text-info">🗑️ Avoid Stop Words</h5>
                                <div class="mb-3">
                                    <strong>Remove unnecessary words (e.g., "a," "the," "and", "of"):</strong><br>
                                    <span class="text-success">✅ <code>example.com/learn-seo</code></span><br>
                                    <span class="text-danger">❌ <code>example.com/how-to-learn-seo</code></span>
                                </div>
                                <p><small class="text-muted">Keep URLs concise while maintaining readability</small></p>
                            </div>
                        </div>


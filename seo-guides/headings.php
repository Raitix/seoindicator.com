                        <h2 class="card-title text-primary mb-3">What are HTML Headings?</h2>
                        <p class="card-text">
                            HTML headings (H1-H6) are structural elements that define the hierarchy and organization of content on a web page. They create a clear outline that helps both users and search engines understand the structure and importance of different sections. The H1 tag represents the main heading, while H2-H6 tags create subheadings in decreasing order of importance.
                        </p>
                        <div class="bg-secondary p-3 rounded mt-3">
                            <strong>HTML Heading Structure:</strong><br>
                            <code>&lt;h1&gt;Main Page Title&lt;/h1&gt;<br>
                            &lt;h2&gt;Section Heading&lt;/h2&gt;<br>
                            &nbsp;&nbsp;&lt;h3&gt;Subsection Heading&lt;/h3&gt;<br>
                            &nbsp;&nbsp;&lt;h3&gt;Another Subsection&lt;/h3&gt;<br>
                            &lt;h2&gt;Next Major Section&lt;/h2&gt;<br>
                            &nbsp;&nbsp;&lt;h3&gt;Subsection Under H2&lt;/h3&gt;<br>
                            &nbsp;&nbsp;&nbsp;&nbsp;&lt;h4&gt;Sub-subsection&lt;/h4&gt;</code>
                        </div>
                    </div>
                </div>

                <div class="card bg-dark border-secondary mb-4">

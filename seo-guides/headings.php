                        <div class="row">
                            <div class="col-md-6">
                                <h5 class="text-warning">❌ What NOT to Do:</h5>
                                <ul class="text-danger">
                                    <li>Using multiple H1 tags on one page</li>
                                    <li>Skipping heading levels (H1 → H3)</li>
                                    <li>Using headings only for styling purposes</li>
                                    <li>Stuffing keywords unnaturally</li>
                                    <li>Making headings too long or vague</li>
                                    <li>Using headings for non-heading content</li>
                                    <li>Inconsistent heading structure</li>
                                    <li>No headings at all beyond H1</li>

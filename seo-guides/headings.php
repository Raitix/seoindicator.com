                            <small class="text-muted">Clear hierarchy with logical flow and keyword-rich headings</small></p>
                            
                            <p class="mb-2"><strong>Product Page Structure:</strong><br>
                            <code>H1: "iPhone 15 Pro - Advanced Photography Features"<br>
                            H2: "Key Features and Specifications"<br>
                            &nbsp;&nbsp;H3: "Camera System"<br>
                            &nbsp;&nbsp;H3: "Performance and Battery"<br>
                            H2: "Customer Reviews and Ratings"<br>
                            H2: "Pricing and Availability"</code><br>
                            <small class="text-muted">Product-focused with clear sections for user decision-making</small></p>
                            
                            <p class="mb-0"><strong>Service Page Structure:</strong><br>
                            <code>H1: "Professional Web Design Services in Chicago"<br>
                            H2: "Our Web Design Process"<br>

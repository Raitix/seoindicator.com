                <div class="card bg-dark border-secondary mb-4">
                    <div class="card-body">
                        <h2 class="card-title text-warning mb-3">SEO Best Practices for Headings</h2>
                        
                        <div class="row">
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">🏗️ Hierarchical Structure</h5>
                                <ul>
                                    <li>Use <strong>only one H1</strong> per page</li>
                                    <li>Follow logical order: H1 → H2 → H3 → H4</li>
                                    <li>Don't skip heading levels (H1 → H3)</li>
                                    <li>Use headings to outline content structure</li>
                                </ul>
                            </div>
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">🎯 Keyword Optimization</h5>
                                <ul>
                                    <li>Include <strong>target keywords</strong> naturally</li>
                                    <li>Use variations and long-tail keywords</li>
                                    <li>Avoid keyword stuffing in headings</li>
                                    <li>Match search intent with heading content</li>
                                </ul>
                            </div>
                        </div>

                        <div class="row">
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">📝 Content Quality</h5>
                                <ul>
                                    <li>Make headings <strong>descriptive</strong> and specific</li>
                                    <li>Keep concise (under 70 characters for H1/H2)</li>
                                    <li>Use action words when appropriate</li>
                                    <li>Ensure headings match the content below</li>
                                </ul>
                            </div>
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">🎨 Formatting Guidelines</h5>
                                <ul>
                                    <li>Use proper capitalization (Title Case or Sentence case)</li>
                                    <li>Avoid excessive punctuation</li>
                                    <li>Keep headings scannable and readable</li>
                                    <li>Maintain consistent formatting style</li>
                                </ul>
                            </div>
                        </div>
                    </div>

                        <h5 class="text-danger">❌ Poor Examples:</h5>
                        <div class="bg-danger bg-opacity-10 p-3 rounded">
                            <p class="mb-2"><strong>Multiple H1 Tags:</strong><br>
                            <code>H1: "Welcome to Our Site"<br>
                            H1: "Our Services"<br>
                            H1: "Contact Us"</code><br>
                            <small class="text-muted">Multiple H1s confuse search engines about main topic</small></p>
                            
                            <p class="mb-2"><strong>Skipped Hierarchy:</strong><br>
                            <code>H1: "Main Title"<br>
                            H4: "Subsection"<br>
                            H2: "Another Section"</code><br>
                            <small class="text-muted">Skipping H2 and H3 breaks logical structure</small></p>
                            
                            <p class="mb-0"><strong>Non-Descriptive Headings:</strong><br>
                            <code>H1: "Welcome"<br>
                            H2: "Section 1"<br>
                            H2: "More Info"</code><br>
                            <small class="text-muted">Vague headings provide no context or SEO value</small></p>

                                    <li>Natural, compelling language</li>
                                    <li>Specific, descriptive content</li>
                                    <li>Accurate representation of page content</li>
                                    <li>Optimal length (120-160 characters)</li>
                                    <li>Include relevant keywords naturally</li>
                                    <li>Every important page has a meta description</li>

                        <h2 class="card-title text-warning mb-3">SEO Best Practices for Meta Descriptions</h2>
                        
                        <div class="row">
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">📏 Optimal Length</h5>
                                <ul>
                                    <li><strong>150-160 characters</strong> to avoid truncation in search results</li>
                                    <li>Google typically displays up to 160 characters</li>
                                    <li>Mobile may show fewer characters</li>
                                    <li>Aim for 120-150 characters for safety</li>
                                </ul>
                            </div>
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">🎯 Keyword Usage</h5>
                                <ul>
                                    <li>Include <strong>primary keywords</strong> naturally</li>
                                    <li>Keywords in meta descriptions get bolded in search results</li>
                                    <li>Use variations and related terms</li>
                                    <li>Don't keyword stuff - focus on readability</li>
                                </ul>
                            </div>
                        </div>

                        <div class="row">
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">💬 Compelling Copy</h5>
                                <ul>
                                    <li>Write in <strong>active voice</strong></li>
                                    <li>Include a clear call-to-action</li>
                                    <li>Address user pain points or benefits</li>
                                    <li>Create urgency or curiosity when appropriate</li>
                                </ul>
                            </div>
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">🎨 Formatting Tips</h5>
                                <ul>
                                    <li>Use proper punctuation and grammar</li>
                                    <li>Avoid special characters that may break display</li>
                                    <li>Consider using numbers or statistics</li>
                                    <li>Make each description unique</li>
                                </ul>
                            </div>
                        </div>

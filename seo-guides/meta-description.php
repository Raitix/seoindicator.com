                        <h2 class="card-title text-primary mb-3">What is a Meta Description?</h2>
                        <p class="card-text">
                            A meta description is an HTML attribute that provides a brief summary of a web page's content. It appears in search engine results pages (SERPs) below the title tag and URL, giving users a preview of what they can expect to find on your page. Meta descriptions are defined within the <code>&lt;head&gt;</code> section of your HTML document.
                        </p>
                        <div class="bg-secondary p-3 rounded mt-3">
                            <strong>HTML Example:</strong><br>
                            <code>&lt;head&gt;<br>
                            &nbsp;&nbsp;&lt;meta name="description" content="Your compelling page description here that summarizes the content and encourages clicks."&gt;<br>
                            &lt;/head&gt;</code>
                        </div>
                    </div>
                </div>


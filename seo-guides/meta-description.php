                        <div class="row">
                            <div class="col-md-6">
                                <h5 class="text-warning">❌ What NOT to Do:</h5>
                                <ul class="text-danger">
                                    <li>Duplicate descriptions across pages</li>
                                    <li>Keyword stuffing or unnatural language</li>
                                    <li>Generic descriptions like "Welcome to our site"</li>
                                    <li>Descriptions that don't match page content</li>
                                    <li>Too short (under 120 characters)</li>
                                    <li>Too long (over 160 characters)</li>
                                    <li>Missing meta descriptions entirely</li>
                                    <li>Using only company/brand name</li>
                                </ul>
                            </div>

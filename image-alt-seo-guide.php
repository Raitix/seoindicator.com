                    <div class="card-body">
                        <h2 class="card-title text-info mb-3">Image Alt Examples</h2>
                        
                        <h5 class="text-success">✅ Good Examples:</h5>
                        <div class="bg-success bg-opacity-10 p-3 rounded mb-3">
                            <p class="mb-2"><strong>Product Images:</strong><br>
                            <code>alt="iPhone 15 Pro in titanium finish showing camera system"</code><br>
                            <code>alt="Red Nike Air Max sneakers size 10 on white background"</code><br>
                            <small class="text-muted">Specific product details that help with product search</small></p>
                            
                            <p class="mb-2"><strong>Informational Images:</strong><br>
                            <code>alt="Bar chart showing website traffic increase of 150% from January to December 2024"</code><br>
                            <code>alt="Step-by-step infographic: how to install WordPress in 5 easy steps"</code><br>
                            <small class="text-muted">Clear description of data and information conveyed</small></p>
                            
                            <p class="mb-2"><strong>People and Events:</strong><br>
                            <code>alt="CEO Sarah Johnson presenting quarterly results at company conference"</code><br>
                            <code>alt="Team of developers working together on laptop computers in modern office"</code><br>
                            <small class="text-muted">Context and action, not just appearance</small></p>
                            
                            <p class="mb-2"><strong>Logos and Branding:</strong><br>
                            <code>alt="Nike logo"</code><br>
                            <code>alt="Microsoft logo"</code><br>
                            <code>alt="WordPress logo in blue and white"</code><br>
                            <small class="text-muted">Simple brand identification without unnecessary words</small></p>
                            
                            <p class="mb-2"><strong>Buttons and CTAs:</strong><br>
                            <code>alt="Download PDF"</code><br>
                            <code>alt="Subscribe to newsletter"</code><br>
                            <code>alt="Add to cart"</code><br>
                            <small class="text-muted">Focus on the action, not the visual appearance</small></p>
                            
                            <p class="mb-0"><strong>Decorative Images:</strong><br>
                            <code>alt=""</code> (empty for purely decorative elements)<br>
                            <code>alt="decorative border pattern"</code> (if it adds context)<br>
                            <small class="text-muted">Empty alt for decoration, descriptive if meaningful</small></p>
                        </div>

                        <h5 class="text-danger">❌ Poor Examples:</h5>
                        <div class="bg-danger bg-opacity-10 p-3 rounded">
                            <p class="mb-2"><strong>Too Generic:</strong><br>
                            <code>alt="image"</code> or <code>alt="photo"</code><br>
                            <small class="text-muted">Provides no useful information</small></p>
                            
                            <p class="mb-2"><strong>Keyword Stuffing:</strong><br>
                            <code>alt="best SEO agency top SEO services SEO experts professional SEO company"</code><br>
                            <small class="text-muted">Unnatural keyword repetition</small></p>
                            
                            <p class="mb-2"><strong>Too Long:</strong><br>
                            <code>alt="This is a beautiful high-resolution photograph showing our amazing team of professional web developers and designers working hard in their state-of-the-art modern office space with the latest technology and equipment to create stunning websites for clients worldwide"</code><br>
                            <small class="text-muted">Unnecessarily verbose and difficult to process</small></p>
                            
                            <p class="mb-2"><strong>File Names:</strong><br>
                            <code>alt="IMG_20241201_photo.jpg"</code><br>
                            <small class="text-muted">Technical file names provide no context</small></p>
                            
                            <p class="mb-2"><strong>Logo Mistakes:</strong><br>
                            <code>alt="Company logo image of Nike swoosh brand symbol"</code><br>
                            <code>alt="Image of our beautiful company logo design"</code><br>
                            <small class="text-muted">Overly verbose when simple "Nike logo" would suffice</small></p>
                            
                            <p class="mb-0"><strong>Button/CTA Mistakes:</strong><br>
                            <code>alt="Red rectangular download button with white text"</code><br>
                            <code>alt="Click here image button"</code><br>
                            <small class="text-muted">Describes appearance instead of function</small></p>

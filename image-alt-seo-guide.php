                        <h2 class="card-title text-primary mb-3">What are Image Alt Attributes?</h2>
                        <p class="card-text">
                            Image alt attributes (alternative text) are HTML attributes that provide text descriptions of images for screen readers, search engines, and situations where images cannot be displayed. They serve as essential accessibility features and SEO elements that describe the content and function of images on web pages.
                        </p>
                        <div class="bg-secondary p-3 rounded mt-3">
                            <strong>HTML Alt Attribute Syntax:</strong><br>
                            <code>&lt;img src="image.jpg" alt="Descriptive text about the image"&gt;<br>
                            &lt;img src="logo.png" alt="Company Name - Professional Web Design Services"&gt;<br>
                            &lt;img src="chart.png" alt="Sales growth chart showing 25% increase in Q4 2024"&gt;<br>
                            &lt;img src="decorative.jpg" alt=""&gt; &lt;!-- Decorative images can have empty alt --&gt;</code>
                        </div>
                    </div>
                </div>


                <div class="card bg-dark border-secondary mb-4">
                    <div class="card-body">
                        <h2 class="card-title text-warning mb-3">SEO Best Practices for Image Alt Attributes</h2>
                        
                        <div class="row">
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">📝 Content Guidelines</h5>
                                <ul>
                                    <li>Be <strong>descriptive and specific</strong></li>
                                    <li>Keep under 125 characters (screen reader limit)</li>
                                    <li>Describe the image content and context</li>
                                    <li>Include relevant keywords naturally</li>
                                    <li>Avoid starting with "Image of" or "Picture of"</li>
                                    <li>For logos: Use "[Brand] logo" format (e.g., "Nike logo")</li>
                                    <li>For buttons/CTAs: Describe the action (e.g., "Download PDF")</li>
                                </ul>
                            </div>
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">🎯 SEO Optimization</h5>
                                <ul>
                                    <li>Include <strong>target keywords</strong> when relevant</li>
                                    <li>Match alt text to page topic and intent</li>
                                    <li>Use variations for multiple similar images</li>
                                    <li>Consider image function, not just appearance</li>
                                    <li>Optimize for image search visibility</li>
                                    <li>Avoid repetition with captions or nearby text</li>
                                </ul>
                            </div>
                        </div>

                        <div class="row">
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">♿ Accessibility Focus</h5>
                                <ul>
                                    <li>Write for <strong>screen reader users</strong> first</li>
                                    <li>Convey essential information clearly</li>
                                    <li>Use empty alt="" for decorative images</li>
                                    <li>Describe charts and graphs meaningfully</li>
                                    <li>Include text content from images</li>
                                </ul>
                            </div>
                            <div class="col-md-6 mb-3">
                                <h5 class="text-info">🎨 Technical Guidelines</h5>
                                <ul>
                                    <li>Use proper HTML syntax</li>
                                    <li>Avoid special characters when possible</li>
                                    <li>Write in sentence case</li>
                                    <li>End with punctuation for complete sentences</li>
                                    <li>Test with screen readers</li>
                                </ul>
                            </div>
                        </div>
                    </div>
                </div>

                <div class="card bg-dark border-secondary mb-4">
                    <div class="card-body">
                        <h2 class="card-title text-danger mb-3">Common Image Alt Mistakes to Avoid</h2>
                        <div class="row">
                            <div class="col-md-6">
                                <h5 class="text-warning">❌ What NOT to Do:</h5>
                                <ul class="text-danger">
                                    <li>Leaving alt attributes empty for content images</li>
                                    <li>Using "image", "photo", "picture" unnecessarily</li>
                                    <li>Keyword stuffing with irrelevant terms</li>
                                    <li>Writing overly long descriptions (200+ chars)</li>
                                    <li>Using identical alt text for different images</li>
                                    <li>Including file names (image001.jpg)</li>
                                    <li>Adding alt text to decorative images</li>
                                    <li>Using alt text for complex infographics without additional context</li>
                                </ul>
                            </div>
                            <div class="col-md-6">
                                <h5 class="text-success">✅ What TO Do:</h5>
                                <ul class="text-success">
                                    <li>Provide meaningful descriptions for all content images</li>
                                    <li>Focus on the image's purpose and content</li>
                                    <li>Include keywords naturally and contextually</li>
                                    <li>Keep descriptions concise but informative</li>
                                    <li>Create unique descriptions for each image</li>
                                    <li>Describe what users need to know</li>
                                    <li>Use empty alt="" only for decorative elements</li>
                                    <li>Provide detailed descriptions for informational graphics</li>
                                </ul>
                            </div>
                        </div>
